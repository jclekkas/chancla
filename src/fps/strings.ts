export const STRINGS: Record<Lang, Record<Key, string>> = { en, es };

let lang: Lang = 'en';
const subs = new Set<(l: Lang) => void>();

export function getLang(): Lang { return lang; }
export function setLang(l: Lang): void { lang = l === 'es' ? 'es' : 'en'; for (const f of subs) f(lang); }
export function onLang(f: (l: Lang) => void): () => void { subs.add(f); return () => subs.delete(f); }
export function detectLang(): Lang { return (typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('es')) ? 'es' : 'en'; }
export function hasKey(k: string): k is Key { return k in en; }

export function t(key: Key, params?: Record<string, string | number>): string {
  let s = STRINGS[lang][key] ?? en[key] ?? key;
  if (params) for (const k of Object.keys(params)) s = s.replaceAll(`{${k}}`, String(params[k]));
  return s;
}

export function applyDom(root: ParentNode): void {
  root.querySelectorAll<HTMLElement>('[data-t]').forEach((el) => { el.textContent = t(el.dataset.t as Key); });
  root.querySelectorAll<HTMLElement>('[data-t-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.tAria as Key)));
  root.querySelectorAll<HTMLElement>('[data-t-ph]').forEach((el) => el.setAttribute('placeholder', t(el.dataset.tPh as Key)));
  root.querySelectorAll<HTMLElement>('[data-t-alt]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.tAlt as Key)));
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang;
    document.title = t('meta.title');
  }
}
